#!/usr/bin/env node
// Turn per-state JSON files into idempotent SQL for All-State Layer 1.
//
//   node scripts/load-all-state-json.mjs <dir> > /tmp/states.sql
//
// This exists because 50 states hand-written as 50 migrations is 50 chances to
// repeat the same SQL mistake, and because "adding a state is data entry" is
// only true if there is something that eats the data. Each state is one JSON
// file matching SCHEMA.md; this emits the inserts.
//
// Everything is guarded so a re-run is a no-op: programs upsert on
// (lineage_key, season), children are inserted only when an identical row is
// not already present. Rows are staged as pending_verification — publishing
// stays a separate, human act.

import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: load-all-state-json.mjs <dir>'); process.exit(1); }

/** Single-quote escape for SQL literals. */
const q = (v) => (v === undefined || v === null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v === undefined || v === null || v === '' || Number.isNaN(Number(v)) ? 'NULL' : String(Number(v)));
const bool = (v) => (v ? 'TRUE' : 'FALSE');

/** Dates arrive as "2026-09-15" or full ISO. Emit a timestamptz literal or NULL. */
function ts(v, tz) {
  if (!v) return 'NULL';
  const s = String(v).trim();
  const iso = /^\d{4}-\d{2}-\d{2}$/.test(s) ? `${s} 00:00:00` : s;
  return `(${q(iso)}::timestamp AT TIME ZONE ${q(tz || 'America/New_York')})`;
}

const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
const out = [];
const report = [];

out.push('-- GENERATED by scripts/load-all-state-json.mjs — do not edit by hand.');
out.push('-- Regenerate from the per-state JSON files. Idempotent: safe to re-run.');
out.push('BEGIN;');

for (const file of files) {
  let doc;
  try {
    doc = JSON.parse(readFileSync(join(dir, file), 'utf8'));
  } catch (e) {
    report.push(`SKIP ${file} — invalid JSON: ${e.message}`);
    continue;
  }
  const slug = doc.state_slug;
  if (!slug) { report.push(`SKIP ${file} — no state_slug`); continue; }
  if (doc.no_program_found) {
    report.push(`NONE ${slug} — ${doc.notes || 'no chorus program found'}`);
    continue;
  }
  if (!doc.organization?.name || !Array.isArray(doc.programs) || doc.programs.length === 0) {
    report.push(`SKIP ${slug} — missing organization or programs`);
    continue;
  }

  const ret = ts(doc.retrieved_at, 'America/New_York');
  const org = doc.organization;

  out.push(`\n-- ───── ${slug} ─────`);
  out.push(
    `INSERT INTO public.gw_all_state_organizations (state_id,name,acronym,website_url,description)
SELECT s.id,${q(org.name)},${q(org.acronym)},${q(org.website_url)},${q(org.description)}
  FROM public.gw_all_state_states s WHERE s.slug=${q(slug)}
ON CONFLICT (state_id,name) DO NOTHING;`);

  for (const src of doc.sources ?? []) {
    if (!src?.url) continue;
    out.push(
      `INSERT INTO public.gw_all_state_sources (state_id,organization_id,name,domain,url,source_type,trust_level,retrieved_at)
SELECT s.id,o.id,${q(src.name || src.url)},NULL,${q(src.url)},${q(src.source_type || 'official')},'official',${ret}
  FROM public.gw_all_state_states s
  JOIN public.gw_all_state_organizations o ON o.state_id=s.id AND o.name=${q(org.name)}
 WHERE s.slug=${q(slug)}
   AND NOT EXISTS (SELECT 1 FROM public.gw_all_state_sources x WHERE x.url=${q(src.url)});`);
  }

  let nDates = 0, nReqs = 0, nRep = 0, nFees = 0, nDocs = 0, nParts = 0;

  for (const p of doc.programs) {
    if (!p?.name || !p?.lineage_key || !p?.season) {
      report.push(`  skip program in ${slug} — missing name/lineage_key/season`);
      continue;
    }
    const pslug = `${p.lineage_key}-${String(p.season).replace(/[^a-z0-9]+/gi, '-').toLowerCase()}`;
    out.push(
      `INSERT INTO public.gw_all_state_programs
 (state_id,organization_id,name,slug,season,lineage_key,school_level,ensemble_type,description,verification_status)
SELECT s.id,o.id,${q(p.name)},${q(pslug)},${q(p.season)},${q(p.lineage_key)},
       ${q(p.school_level)},${q(p.ensemble_type)},${q(p.description)},'pending_verification'
  FROM public.gw_all_state_states s
  JOIN public.gw_all_state_organizations o ON o.state_id=s.id AND o.name=${q(org.name)}
 WHERE s.slug=${q(slug)}
ON CONFLICT (lineage_key,season) DO NOTHING;`);

    const P = `(SELECT id FROM public.gw_all_state_programs WHERE slug=${q(pslug)})`;
    const SRC = (u) => `(SELECT id FROM public.gw_all_state_sources WHERE url=${q(u)} LIMIT 1)`;

    for (const d of p.dates ?? []) {
      if (!d?.title) continue;
      nDates++;
      const tz = d.timezone || 'America/New_York';
      out.push(
        `INSERT INTO public.gw_all_state_dates
 (program_id,date_type,title,start_at,end_at,all_day,timezone,description,source_id,source_url,retrieved_at,confidence,sort_order)
SELECT ${P},${q(d.date_type || 'other')},${q(d.title)},${ts(d.start_at, tz)},${ts(d.end_at, tz)},
       ${bool(d.all_day !== false)},${q(tz)},${q(d.description)},${SRC(d.source_url)},${q(d.source_url)},${ret},'official_source',${num(d.sort_order ?? 100)}
 WHERE ${P} IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM public.gw_all_state_dates x WHERE x.program_id=${P} AND x.title=${q(d.title)});`);
    }

    for (const r of p.requirements ?? []) {
      if (!r?.title) continue;
      nReqs++;
      out.push(
        `INSERT INTO public.gw_all_state_requirements
 (program_id,category,title,description,structured_data,source_id,source_url,retrieved_at,confidence,sort_order)
SELECT ${P},${q(r.category || 'other')},${q(r.title)},${q(r.description)},
       ${q(JSON.stringify(r.structured_data ?? {}))}::jsonb,${SRC(r.source_url)},${q(r.source_url)},${ret},'official_source',${num(r.sort_order ?? 100)}
 WHERE ${P} IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM public.gw_all_state_requirements x WHERE x.program_id=${P} AND x.title=${q(r.title)});`);
    }

    for (const r of p.repertoire ?? []) {
      if (!r?.title) continue;
      nRep++;
      out.push(
        `INSERT INTO public.gw_all_state_repertoire
 (program_id,title,composer,arranger,publisher,catalog_number,voicing,purpose,movement,notes,source_url,sort_order)
SELECT ${P},${q(r.title)},${q(r.composer)},${q(r.arranger)},${q(r.publisher)},${q(r.catalog_number)},
       ${q(r.voicing)},${q(r.purpose || 'audition')},${q(r.movement)},${q(r.notes)},${q(r.source_url)},${num(r.sort_order ?? 100)}
 WHERE ${P} IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM public.gw_all_state_repertoire x WHERE x.program_id=${P} AND x.title=${q(r.title)});`);
    }

    for (const f of p.fees ?? []) {
      if (!f?.fee_type) continue;
      nFees++;
      out.push(
        `INSERT INTO public.gw_all_state_fees
 (program_id,fee_type,amount_cents,currency,payable_to,description,source_id,source_url,retrieved_at,confidence)
SELECT ${P},${q(f.fee_type)},${num(f.amount_cents)},'usd',${q(f.payable_to || 'unknown')},${q(f.description)},
       ${SRC(f.source_url)},${q(f.source_url)},${ret},'official_source'
 WHERE ${P} IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM public.gw_all_state_fees x WHERE x.program_id=${P} AND x.fee_type=${q(f.fee_type)});`);
    }

    for (const d of p.documents ?? []) {
      if (!d?.title || !d?.url) continue;
      nDocs++;
      out.push(
        `INSERT INTO public.gw_all_state_documents
 (program_id,title,document_type,url,published_at,retrieved_at,source_id,sort_order)
SELECT ${P},${q(d.title)},${q(d.document_type)},${q(d.url)},${ts(d.published_at, 'America/New_York')},${ret},${SRC(d.url)},${num(d.sort_order ?? 100)}
 WHERE ${P} IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM public.gw_all_state_documents x WHERE x.program_id=${P} AND x.url=${q(d.url)});`);
    }

    (p.voice_parts ?? []).forEach((v, i) => {
      if (!v?.code || !v?.label) return;
      nParts++;
      out.push(
        `INSERT INTO public.gw_all_state_voice_parts (program_id,code,label,sort_order)
SELECT ${P},${q(v.code)},${q(v.label)},${num(v.sort_order ?? (i + 1) * 10)}
 WHERE ${P} IS NOT NULL
ON CONFLICT (program_id,code) DO NOTHING;`);
    });
  }

  report.push(
    `OK   ${slug.padEnd(22)} programs=${doc.programs.length} dates=${nDates} reqs=${nReqs} rep=${nRep} fees=${nFees} docs=${nDocs} parts=${nParts}` +
    (doc.not_published?.length ? `  (${doc.not_published.length} gaps noted)` : ''));
}

out.push('\nCOMMIT;');
out.push("NOTIFY pgrst, 'reload schema';");

console.log(out.join('\n'));
console.error(report.join('\n'));
console.error(`\n${files.length} file(s) processed.`);
